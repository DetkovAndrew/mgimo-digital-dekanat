-- Аудит вымышленности NursuUwU (11.11, docs/research/fictional-data-audit.md): два ФИО совпали с реальными
-- сотрудниками вузов, тексты обещали PDF с подписью. Повторяет правки prisma/seed.ts для уже заполненных баз,
-- не стирая данные. Идемпотентно: повторный запуск ничего не меняет.
-- Запуск: psql -v ON_ERROR_STOP=1 -f prisma/data-fixes/2026-11-14-fictional-names.sql
BEGIN;
UPDATE "teacher" SET "fullName" = 'Деморина Ирина Викторовна' WHERE "fullName" = 'Шульц Ирина Викторовна';
UPDATE "sport_slot" SET "coach" = 'Слотвина Олеся Андреевна' WHERE "coach" = 'Гусева Олеся Андреевна';

UPDATE "request_event" SET "comment" = 'Демонстрационная справка подготовлена. Файл и электронная подпись в прототипе не выдаются.'
  WHERE "comment" = 'Справка подписана электронной подписью, PDF доступен';
UPDATE "request_event" SET "comment" = 'Уточните, в какие дни сможете посещать практические занятия по дискретной математике.'
  WHERE "comment" = 'Уточните, в какие дни сможете посещать практики по дискретной математике.';
UPDATE "notification" SET "body" = replace("body", 'Справка подписана электронной подписью, PDF доступен', 'Демонстрационная справка подготовлена. Файл и электронная подпись в прототипе не выдаются.')
  WHERE "body" LIKE '%Справка подписана электронной подписью, PDF доступен%';
UPDATE "notification" SET "body" = replace("body", 'посещать практики по дискретной', 'посещать практические занятия по дискретной')
  WHERE "body" LIKE '%посещать практики по дискретной%';

UPDATE "notification" SET "body" = 'Демонстрационные даты экзаменов уже доступны в разделе «Учёба». Сессия: 28 декабря — 31 января. Перед экзаменом проверьте дату ещё раз.'
  WHERE "body" = 'Расписание экзаменов опубликуют 10 декабря — даты появятся в разделе «Учёба». Сессия: 28 декабря — 31 января.';
UPDATE "notification" SET "body" = 'Демонстрационное напоминание: если срок действия проездного истекает в декабре, уточните порядок продления через «Вопрос в деканат» в разделе «Заявки».'
  WHERE "body" = 'Если срок действия социальной карты истекает в декабре — подайте заявление до 15 декабря.';
COMMIT;
