-- Тексты без «нейрослопа» (капитан, 19.11): курсы называются полностью, как в учебном плане, — без «Дискретки», «АиСД»
-- и двуязычного «English B2 / Английский язык B2». Повторяет правки prisma/seed.ts для заполненных баз, не стирая данные:
-- дисциплины, уже разосланные уведомления (сроки, переносы, отмены) и описания секций физкультуры.
-- Идемпотентно. Запуск: psql -v ON_ERROR_STOP=1 -f prisma/data-fixes/2026-11-19-plain-course-names.sql
BEGIN;
UPDATE "discipline" SET "title" = 'Английский язык C1' WHERE "title" = 'English C1 / Английский язык C1';
UPDATE "discipline" SET "title" = 'Английский язык B2' WHERE "title" = 'English B2 / Английский язык B2';
UPDATE "discipline" SET "title" = 'Английский язык B1' WHERE "title" = 'English B1 / Английский язык B1';
UPDATE "discipline" SET "shortTitle" = NULL WHERE "shortTitle" IN ('Английский C1', 'Английский B2', 'АиСД', 'Java', 'Дискретка');

-- Краткое название стоит только в системных уведомлениях (сроки, переносы и отмены пар): в заголовке после «Изменение: »,
-- «Отмена: », «Снова по расписанию: » или в конце после « — », в тексте — в кавычках «…». Объявления деканата — свободный
-- текст, их не трогаем (ревью Codex 93). Пары заменяются по очереди: одно уведомление может содержать два названия.
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT * FROM (VALUES
    ('Английский C1', 'Английский язык C1'), ('Английский B2', 'Английский язык B2'), ('АиСД', 'Алгоритмы и структуры данных'),
    ('Java', 'Программирование на Java'), ('Дискретка', 'Дискретная математика')) AS v(old, new)
  LOOP
    UPDATE "notification" SET
      "title" = regexp_replace("title", '^(Изменение: |Отмена: |Снова по расписанию: |Срок через неделю: .* — )' || r.old || '$', '\1' || r.new),
      "body" = replace("body", '«' || r.old || '»', '«' || r.new || '»')
    WHERE "kind" IN ('SCHEDULE_CHANGE', 'DEADLINE')
      AND ("title" ~ ('^(Изменение: |Отмена: |Снова по расписанию: |Срок через неделю: .* — )' || r.old || '$') OR "body" LIKE '%«' || r.old || '»%');
  END LOOP;
END $$;

UPDATE "sport_section" SET "description" = 'Игровые тренировки для любого уровня подготовки.' WHERE "description" = 'Игровые тренировки, уровень — любой.';
UPDATE "sport_section" SET "description" = 'Функциональные тренировки в зале.' WHERE "description" = 'Функциональный тренинг в зале.';
COMMIT;
