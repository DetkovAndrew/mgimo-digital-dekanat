// docs/agent-eval/results-2026-11-14.md): с функциями «на всякий случай» GigaChat отвечал списком свободных аудиторий
// на вопросы о парах, физкультуре и справках. Теперь функции есть, только если разговор сейчас о брони или свободном месте.

// Без \b: в JS он не видит границ кириллических слов. «Не буква» до и после — вручную.
const W = "(?:^|[^а-яё])";

const ROOM = [
  new RegExp(`${W}(?:за)?брон(?:ь|и|ю|ей|ир)`, "i"), // бронь, забронируй, бронирование (но не «бронхит»)
  /коворкинг|переговорн/i,
  /позанимат|поработат|посидет|тих\S*\s+(мест|зон)/i, // где позаниматься, тихое место
  /где\s+(\S+\s+){0,2}свободн/i, // где свободно завтра
  /(свободн|заня|найд|найт|поищ|ищу|подбер|нужн)\S*\s+(\S+\s+){0,2}(аудитор|комнат|помещени)/i, // найди аудиторию
  /(аудитор|комнат|помещени)\S*\s+(\S+\s+){0,2}(свободн|на\s+\d)/i, // аудитория свободна, аудиторию на 2 часа
  /(свободн|занят)\S*\s+(ли\s+)?(\S+\s+)?\d{4}(?!\d)|(?<!\d)\d{4}\s+(\S+\s+){0,2}свободн/i, // свободна ли 1206
];

// Уточнение — короткая реплика только из дня, времени, длительности, места или согласия («В четверг», «С 14:00»,
// «На два часа», «После пар», «Давай»). Всё остальное — новый вопрос, и он сбрасывает тему (ревью Codex 53–54).
const TOKENS = new Set([
  "да", "ок", "окей", "давай", "давайте", "хорошо", "подходит", "можно", "тогда", "а", "и", "или", "в", "во", "на", "с", "со", "до",
  "после", "к", "по", "около", "час", "часа", "часов", "полчаса", "минут", "один", "одну", "два", "две", "три", "четыре",
  "человек", "мест", "места", "корпус", "корпусе", "главном", "главный", "ломоносова", "кронверкском", "кронверкский",
  "утром", "утра", "днём", "днем", "вечером", "вечера", "сегодня", "завтра", "послезавтра", "понедельник", "вторник",
  "среду", "среда", "четверг", "пятницу", "пятница", "субботу", "суббота", "воскресенье", "пар", "пары", "занятий", "обеда",
]);

type Topic = "rooms" | "other" | "follow-up";
const NUMBER = /^(\d{1,2}([:.]\d{2})?|\d{4})$/;

/** Разбиение на слова, а не одно регулярное выражение из коротких слов: то на длинной строке студента работало бы
 *  экспоненциально долго (возврат на «час|часа|а»). Здесь — линейно и не длиннее 8 слов. */
function isFollowUp(text: string) {
  const words = text.toLowerCase().split(/[\s,.!?;]+/).filter(Boolean);
  return words.length > 0 && words.length <= 8 && words.every((w) => TOKENS.has(w) || NUMBER.test(w));
}

export const topicOf = (text: string): Topic => (ROOM.some((re) => re.test(text)) ? "rooms" : isFollowUp(text) ? "follow-up" : "other");

/**
 * По последней реплике студента, у которой есть тема. Уточнения («в четверг», «с 14:00», «на два часа») тему
 * наследуют, вопрос о другом её сбрасывает (ревью Codex 53). Реплики помощника не в счёт.
 */
export function wantsRooms(messages: readonly { role: string; content: string }[]): boolean {
  const said = messages.filter((m) => m.role === "user").map((m) => topicOf(m.content));
  for (let i = said.length - 1; i >= 0; i--) if (said[i] !== "follow-up") return said[i] === "rooms";
  return false;
}
