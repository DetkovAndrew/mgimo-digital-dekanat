import { describe, expect, it } from "vitest";
import { wantsRooms } from "./intent";

const one = (content: string) => wantsRooms([{ role: "user", content }]);

describe("когда давать модели функции аудиторий", () => {
  it.each([
    "Найди свободную аудиторию завтра с 14 до 16",
    "Забронируй мне коворкинг послезавтра с 14 до 16, готовиться к физике",
    "Забронируй 1206 на 12",
    "Где можно позаниматься в среду после пар?",
    "Нужна переговорная на 6 человек",
    "Есть свободные аудитории сейчас?",
    "Хочу занять аудиторию на час",
    "Где свободно завтра после 15?",
    "Аудитория 2101 свободна в четверг?",
    "Поищи аудиторию на завтра",
    "Свободна ли 1206 завтра?",
    "Найди свободную аудиторию после пары",
  ])("да: %s", (q) => expect(one(q)).toBe(true));

  it.each([
    // промахи прогона 14.11
    "Успею ли я во вторник с английского на хемоинформатику?",
    "Подбери физкультуру без пересечений с парами.",
    "Запиши меня на плавание: формат записи выбери сам.",
    "Что нужно для выписки оценок на английском?",
    // про аудиторию пары — это расписание, а не бронь
    "В какой аудитории у меня следующая пара?",
    "Где у меня следующая пара?",
    "Есть ли у меня свободное время в среду?",
    "Закажи справку для военкомата.",
    "У меня бронхит, как подать на академический отпуск?",
  ])("нет: %s", (q) => expect(one(q)).toBe(false));

  const chat = (...user: string[]) => user.flatMap((content) => [{ role: "user", content }, { role: "assistant", content: "…" }]).slice(0, -1);

  it("бронь не теряется за несколькими уточнениями (ревью Codex 53)", () => {
    expect(wantsRooms(chat("Забронируй аудиторию", "В четверг", "С 14:00", "На два часа"))).toBe(true);
  });

  it("уточнения — только явные: «После пар» продолжает бронь, полноценный вопрос сбрасывает (ревью Codex 54)", () => {
    expect(wantsRooms(chat("Забронируй аудиторию", "После пар"))).toBe(true);
    expect(wantsRooms(chat("Найди свободную аудиторию", "Успею ли я во вторник с английского на хемоинформатику?"))).toBe(false);
    expect(wantsRooms(chat("Найди свободную аудиторию", "Поздравь моего кота"))).toBe(false);
  });

  it("длинная реплика студента разбирается быстро", () => {
    const t = performance.now();
    for (const filler of ["часа ".repeat(200), "а".repeat(1000), "свободн ".repeat(120), "1206 ".repeat(200)]) wantsRooms([{ role: "user", content: filler }]);
    expect(performance.now() - t).toBeLessThan(200);
  });

  it("новый вопрос о другом сбрасывает тему аудиторий (ревью Codex 53)", () => {
    expect(wantsRooms(chat("Найди свободную аудиторию", "Подбери физкультуру без пересечений"))).toBe(false);
    expect(wantsRooms(chat("Найди свободную аудиторию", "Какие у меня оценки?", "А в четверг?"))).toBe(false);
  });

  it("уточнение после вопроса про аудиторию", () => {
    expect(
      wantsRooms([
        { role: "user", content: "Где свободно завтра?" },
        { role: "assistant", content: "Свободно: 1206…" },
        { role: "user", content: "Давай на 15:00 на час" },
      ]),
    ).toBe(true);
  });

  it("реплики помощника не включают функции", () => {
    expect(wantsRooms([{ role: "assistant", content: "Забронируйте коворкинг" }, { role: "user", content: "Спасибо" }])).toBe(false);
  });
});
